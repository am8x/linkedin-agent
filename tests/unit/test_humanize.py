class TestHumanizeCommentaryAgent:
    @pytest.mark.asyncio
    async def test_humanize_agent_success_workflow(self) -> None:
        state = _make_state()
        mock_page = MockPage(
            content_html="<div>AI: 15.0%</div>",
            evaluate_text="Humanized output replacing the raw completion cleanly.",
        )
        agent = create_humanize_agent(
            HumanizeConfig(enabled=True, auto_retry=True),
            browser_factory=lambda: mock_page,
        )

        delta = await agent._run_humanize(state)

        assert delta[KEY_HUMANIZE_STATUS] == HumanizeStatus.SUCCESS.value
        assert delta[KEY_AI_DETECTION_SCORE] == 15.0
        assert (
            delta[KEY_HUMANIZED_COMMENTARY]
            == "Humanized output replacing the raw completion cleanly."
        )
        assert delta[KEY_COMMENTARY]["text"] == delta[KEY_HUMANIZED_COMMENTARY]
        assert delta[KEY_COMMENTARY]["humanized"] is True
        assert delta[KEY_COMMENTARY]["ai_detection_score"] == 15.0

    @pytest.mark.asyncio
    async def test_humanize_agent_bypassed_when_disabled(self) -> None:
        state = _make_state()
        factory = MagicMock()
        agent = create_humanize_agent(
            HumanizeConfig(enabled=False),
            browser_factory=factory,
        )

        delta = await agent._run_humanize(state)

        assert delta[KEY_HUMANIZE_STATUS] == HumanizeStatus.BYPASSED.value
        assert delta[KEY_HUMANIZED_COMMENTARY] == "Raw commentary generated by Gemini."
        assert factory.call_count == 0

    @pytest.mark.asyncio
    async def test_humanize_agent_noop_on_upstream_short_circuit(self) -> None:
        state = _make_state()
        state[KEY_EXECUTION_STATUS] = STATUS_NO_NEW_TWEETS
        factory = MagicMock()
        agent = create_humanize_agent(
            HumanizeConfig(enabled=True),
            browser_factory=factory,
        )

        delta = await agent._run_humanize(state)

        assert factory.call_count == 0
        assert delta == {}

    @pytest.mark.asyncio
    async def test_humanize_agent_retries_transient_failure(self) -> None:
        state = _make_state()
        call_count = 0

        def _flaky_browser() -> MockPage:
            nonlocal call_count
            call_count += 1
            if call_count == 1:
                p = MockPage()
                p.goto.side_effect = TimeoutError("Navigation timeout")
                return p
            return MockPage(
                content_html="<div>AI: 9.0%</div>",
                evaluate_text="Success on second attempt.",
            )

        agent = create_humanize_agent(
            HumanizeConfig(enabled=True, auto_retry=True, retry_cooldown_seconds=0.5),
            browser_factory=_flaky_browser,
        )

        delta = await agent._run_humanize(state)

        assert call_count == 2
        assert delta[KEY_HUMANIZE_STATUS] == HumanizeStatus.SUCCESS.value
        assert delta[KEY_HUMANIZED_COMMENTARY] == "Success on second attempt."

    @pytest.mark.asyncio
    async def test_humanize_agent_fails_and_sets_status_when_exhausted(self) -> None:
        state = _make_state()

        def _failing_browser() -> MockPage:
            p = MockPage()
            p.goto.side_effect = TimeoutError("Persistent connection failure")
            return p

        agent = create_humanize_agent(
            HumanizeConfig(enabled=True, auto_retry=True, retry_cooldown_seconds=0.5),
            browser_factory=_failing_browser,
        )

        delta = await agent._run_humanize(state)

        assert delta[KEY_HUMANIZE_STATUS] == HumanizeStatus.FAILED.value
        assert delta[KEY_EXECUTION_STATUS] == STATUS_FAILED_HUMANIZATION
        assert "Persistent connection failure" in delta[KEY_ERROR]

    @pytest.mark.asyncio
    async def test_humanize_agent_with_adk_session_service(self) -> None:
        service = InMemorySessionService()
        initial_state = _make_state()
        session = await service.create_session(
            app_name="sidekick",
            user_id="sidekick",
            state=initial_state,
        )
        mock_page = MockPage(
            content_html="<div>AI: 8.5%</div>",
            evaluate_text="Rewritten commentary copy through ADK session.",
        )
        agent = create_humanize_agent(
            HumanizeConfig(enabled=True),
            browser_factory=lambda: mock_page,
        )

        from google.adk.agents.invocation_context import InvocationContext

        ctx = InvocationContext(
            session=session,
            session_service=service,
            invocation_id="inv-001",
            agent=agent,
        )

        events = []
        async for ev in agent._run_async_impl(ctx):
            events.append(ev)

        assert len(events) == 1
        assert session.state[KEY_HUMANIZE_STATUS] == "SUCCESS"
        assert session.state[KEY_AI_DETECTION_SCORE] == 8.5
        assert (
            session.state[KEY_HUMANIZED_COMMENTARY]
            == "Rewritten commentary copy through ADK session."
        )
