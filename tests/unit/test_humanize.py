class MockLocator:
    """Mock Playwright Locator."""

    def __init__(self, is_visible_val: bool = True) -> None:
        self._visible = is_visible_val
        self.wait_for = AsyncMock()
        self.click = AsyncMock()
        self.fill = AsyncMock()

    @property
    def first(self) -> MockLocator:
        return self

    async def is_visible(self, timeout: int | None = None) -> bool:
        return self._visible


class MockPage:
    """Mock Playwright Page."""

    def __init__(
        self,
        content_html: str = "<div>AI Score: 14.5%</div>",
        evaluate_text: str = "This is the humanized commentary output that is long enough.",
    ) -> None:
        self.goto = AsyncMock()
        self._content_html = content_html
        self._evaluate_text = evaluate_text
        self.evaluate = AsyncMock(side_effect=self._mock_evaluate)
        self.locator = MagicMock(return_value=MockLocator())

    async def content(self) -> str:
        return self._content_html

    def _mock_evaluate(self, script: str, *args: Any) -> Any:
        if "querySelectorAll" in script or "querySelector" in script:
            return self._evaluate_text
        return None


def _make_state() -> dict[str, Any]:
    return {
        KEY_COMMENTARY_RAW: "Raw commentary generated by Gemini.",
        KEY_COMMENTARY: {
            "text": "Raw commentary generated by Gemini.",
            "paragraph_count": 2,
            "character_count": 35,
            "model_name": "gemini-3.8-flash",
            "grounded": True,
        },
    }


class TestDetectAI:
    @pytest.mark.asyncio
    async def test_detect_ai_parses_score_and_classification(self) -> None:
        mock_page = MockPage(
            content_html="<div class='score'>AI Likelihood: 12.5%</div>"
        )
        result = await detect_ai(mock_page, "Sample text", timeout_seconds=5.0)

        assert isinstance(result, AIDetectionResult)
        assert result.ai_probability == 12.5
        assert result.classification == "Human"
        mock_page.goto.assert_awaited_once()

    @pytest.mark.asyncio
    async def test_detect_ai_classifies_high_score_as_ai(self) -> None:
        mock_page = MockPage(content_html="<div class='score'>88.0% probability</div>")
        result = await detect_ai(mock_page, "Sample text", timeout_seconds=5.0)

        assert result.ai_probability == 88.0
        assert result.classification == "AI-generated"


class TestHumanizeText:
    @pytest.mark.asyncio
    async def test_humanize_text_returns_rewritten_string(self) -> None:
        expected = "A natural humanized commentary written with authentic voice."
        mock_page = MockPage(evaluate_text=expected)
