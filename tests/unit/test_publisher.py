    KEY_AI_DETECTION_SCORE,
    KEY_AUTO_PUBLISH,
    KEY_COMMENTARY,
    KEY_COMMENTARY_RAW,
    KEY_DRY_RUN,
    KEY_ERROR,
    KEY_EXECUTION_STATUS,
    KEY_HUMANIZE_STATUS,
