"""Domain models for HumanizeAI pipeline integration."""

from __future__ import annotations

from datetime import UTC, datetime
from enum import StrEnum
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator


class HumanizeStatus(StrEnum):
    """Execution status for the HumanizeAI stage."""

    SUCCESS = "SUCCESS"
    FAILED = "FAILED"
    BYPASSED = "BYPASSED"


class AIDetectionResult(BaseModel):
    """Result of scanning commentary through HumanizeAI detector."""

    model_config = ConfigDict(extra="ignore")

    ai_probability: float = Field(
        ge=0.0,
        le=100.0,
        description="Detected probability of AI generation as a percentage (0.0 to 100.0).",
    )
    classification: str = Field(
        default="AI",
        description="Qualitative label (e.g. 'Human', 'Mixed', 'AI-generated').",
    )
    scanned_at: datetime = Field(
        default_factory=lambda: datetime.now(UTC),
        description="Timestamp when the detection scan was performed.",
    )


class HumanizedCommentary(BaseModel):
    """Result of the HumanizeAI Playwright transformation."""

    model_config = ConfigDict(extra="ignore")

    raw_text: str = Field(
        description="The original style-guided commentary text generated by the LLM.",
    )
    humanized_text: str = Field(
        description="The rewritten text obtained from HumanizeAI, or fallback text if bypassed.",
    )
    detection_score: float | None = Field(
        default=None,
        description="The AI probability percentage returned by the detector.",
    )
    status: HumanizeStatus = Field(
        default=HumanizeStatus.SUCCESS,
        description="Status of the humanization stage.",
    )
    error_message: str | None = Field(
        default=None,
        description="Diagnostic error details if the stage failed or triggered the fail-safe.",
    )
    transformed_at: datetime = Field(
        default_factory=lambda: datetime.now(UTC),
        description="Timestamp of the transformation.",
    )


class TargetCommentDraft(BaseModel):
    """Generated commentary draft and its anti-detection humanization state."""

    model_config = ConfigDict(extra="ignore")

    raw_text: str = Field(
        min_length=10,
        max_length=250,
        description="Initial multimodal completion matching author persona",
    )
    humanized_text: str = Field(
        default="",
        max_length=250,
        description="Rewritten text after passing through HumanizeAI.pro",
    )
    ai_detection_score: float | None = Field(
        default=None,
        ge=0.0,
        le=100.0,
        description="Probability of AI authorship reported by detector",
    )
    humanize_status: Literal[
        "SUCCESS", "FAILED_HUMANIZATION", "BYPASSED", "PENDING"
    ] = "PENDING"
    recovery_action: (
        Literal["PUBLISH_UNHUMANIZED", "RETRY", "REGENERATE", "CANCEL"] | None
    ) = None

    @property
    def publishable_text(self) -> str:
        """The final approved text to post (humanized if available, raw if bypassed)."""
        return self.humanized_text if self.humanized_text else self.raw_text

    @property
    def character_count(self) -> int:
        return len(self.publishable_text)


CommentPublicationStatus = Literal["PUBLISHED", "DRY_RUN", "SKIPPED", "FAILED"]


class CommentPublicationRecord(BaseModel):
    """Result of attempting to publish a comment via official LinkedIn API."""

    model_config = ConfigDict(extra="ignore")

    target_post_urn: str
    actor_urn: str
    comment_text: str
    status: CommentPublicationStatus
    comment_urn: str | None = None
    published_at: datetime | None = None
    error_message: str | None = None

    @field_validator("published_at")
    @classmethod
    def _ensure_utc(cls, v: datetime | None) -> datetime | None:
        if v is None:
            return None
        return v.replace(tzinfo=UTC) if v.tzinfo is None else v.astimezone(UTC)


__all__ = [
    "AIDetectionResult",
    "CommentPublicationRecord",
    "CommentPublicationStatus",
    "HumanizeStatus",
    "HumanizedCommentary",
    "TargetCommentDraft",
]
