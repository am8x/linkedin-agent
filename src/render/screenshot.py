"""Playwright-powered dark-mode tweet card capture.

The engine navigates to the tweet permalink in headless Chromium, injects the
metric-suppression stylesheet/DOM script from :mod:`src.render.styles`,
isolates ``article[data-testid="tweet"]``, and screenshots only that element.

A ``page`` can be injected into :class:`TweetCardRenderer` for tests, which
removes the need for a real browser while still exercising the full capture
code path.
"""

from __future__ import annotations

import struct
from collections.abc import Mapping
from datetime import UTC, datetime
from pathlib import Path
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator

from src.logging import get_logger
from src.render.styles import (
    DEFAULT_VIEWPORT_HEIGHT,
    DEFAULT_VIEWPORT_WIDTH,
    TWEET_CARD_SELECTOR,
    build_capture_script,
    build_capture_styles,
)

logger = get_logger(__name__)

MAX_FILE_SIZE_BYTES = 10 * 1024 * 1024  # LinkedIn image upload ceiling
PNG_MIME_TYPE = "image/png"
PNG_MAGIC = b"\x89PNG\r\n\x1a\n"
DEVICE_SCALE_FACTOR = 2
DEFAULT_OUTPUT_DIR = Path(".assets/screenshots")

# X gates tweet permalinks behind a login wall, so the capture browser must
# replay the ingested session cookies for a card to render at all.
X_COOKIE_DOMAIN = ".x.com"

# Time allowed for fonts, avatars, and embedded media to settle before capture.
SETTLE_MILLISECONDS = 800


class CaptureError(RuntimeError):
    """Raised when the tweet card could not be rendered or captured."""


class ScreenshotConfig(BaseModel):
    """Configures visual capture behaviour for Playwright (per data-model.md)."""

    model_config = ConfigDict(extra="ignore")

    theme: Literal["dark", "light"] = "dark"
    hide_metrics: bool = True
    viewport_width: int = Field(default=DEFAULT_VIEWPORT_WIDTH, ge=320, le=4096)
    viewport_height: int = Field(default=DEFAULT_VIEWPORT_HEIGHT, ge=240, le=4096)
    timeout_seconds: int = Field(default=15, ge=1, le=120)
    output_dir: Path = DEFAULT_OUTPUT_DIR
    device_scale_factor: float = Field(default=DEVICE_SCALE_FACTOR, ge=1.0, le=4.0)

    @property
    def timeout_ms(self) -> int:
        return self.timeout_seconds * 1000

    @property
    def viewport(self) -> dict[str, int]:
        return {"width": self.viewport_width, "height": self.viewport_height}

    def output_path(self, tweet_id: str) -> Path:
        return Path(self.output_dir) / f"{tweet_id}.png"


def build_screenshot_config(
    render_config: Any | None = None,
    *,
    output_dir: str | Path | None = None,
) -> ScreenshotConfig:
    """Adapt a :class:`src.config.RenderConfig` into a ``ScreenshotConfig``."""
    if render_config is None:
        return ScreenshotConfig(
            output_dir=Path(output_dir) if output_dir else DEFAULT_OUTPUT_DIR
        )
    values: dict[str, Any] = {
        "theme": getattr(render_config, "theme", "dark"),
        "hide_metrics": bool(getattr(render_config, "hide_metrics", True)),
        "viewport_width": int(
            getattr(render_config, "viewport_width", DEFAULT_VIEWPORT_WIDTH)
        ),
        "viewport_height": int(
            getattr(render_config, "viewport_height", DEFAULT_VIEWPORT_HEIGHT)
        ),
        "timeout_seconds": int(getattr(render_config, "timeout_seconds", 15)),
    }
    values["output_dir"] = Path(
        output_dir
        if output_dir is not None
        else getattr(render_config, "output_dir", DEFAULT_OUTPUT_DIR)
    )
    return ScreenshotConfig(**values)


def read_png_dimensions(file_path: str | Path) -> tuple[int, int]:
    """Read ``(width, height)`` from a PNG's IHDR chunk without Pillow."""
    path = Path(file_path)
    try:
        with path.open("rb") as handle:
            header = handle.read(24)
    except OSError as exc:
        raise CaptureError(f"Could not read image {path}: {exc}") from exc

    if len(header) < 24 or not header.startswith(PNG_MAGIC):
        raise CaptureError(f"{path} is not a valid PNG image.")
    width, height = struct.unpack(">II", header[16:24])
    return int(width), int(height)


class RenderedAsset(BaseModel):
    """The local screenshot image generated by Playwright (per data-model.md)."""

    model_config = ConfigDict(extra="ignore")

    file_path: Path
    mime_type: str = PNG_MIME_TYPE
    file_size_bytes: int = Field(gt=0)
    width: int = Field(gt=0)
    height: int = Field(gt=0)
    created_at: datetime = Field(default_factory=lambda: datetime.now(UTC))

    @field_validator("mime_type")
    @classmethod
    def _png_only(cls, value: str) -> str:
        if value != PNG_MIME_TYPE:
            raise ValueError(f"only {PNG_MIME_TYPE} cards are supported, got {value!r}")
        return value

    @field_validator("file_path", mode="before")
    @classmethod
    def _coerce_path(cls, value: Any) -> Any:
        return Path(value) if not isinstance(value, Path) else value

    @model_validator(mode="after")
    def _verify_asset(self) -> RenderedAsset:
        if not self.file_path.exists():
            raise ValueError(f"screenshot file does not exist: {self.file_path}")
        actual_size = self.file_path.stat().st_size
        if actual_size != self.file_size_bytes:
            raise ValueError(
                f"screenshot size mismatch: recorded {self.file_size_bytes} bytes, "
                f"file is {actual_size} bytes"
            )
        if self.file_size_bytes > MAX_FILE_SIZE_BYTES:
            raise ValueError(
                f"screenshot is {self.file_size_bytes} bytes which exceeds the "
                f"{MAX_FILE_SIZE_BYTES} byte LinkedIn limit"
            )
        return self

    @classmethod
    def from_file(cls, file_path: str | Path, *, mime_type: str = PNG_MIME_TYPE):
        """Build a validated asset from an existing PNG on disk."""
        path = Path(file_path)
        if not path.exists():
            raise CaptureError(f"Screenshot was not written to {path}")
        size = path.stat().st_size
        width, height = read_png_dimensions(path)
        return cls(
            file_path=path,
            mime_type=mime_type,
            file_size_bytes=size,
            width=width,
            height=height,
        )

    @property
    def size_in_megabytes(self) -> float:
        return self.file_size_bytes / (1024 * 1024)


class TweetCardRenderer:
    """Owns the Playwright lifecycle and captures isolated tweet cards."""

    def __init__(
        self,
        config: ScreenshotConfig | None = None,
        *,
        page: Any | None = None,
        cookies: Mapping[str, str] | None = None,
    ) -> None:
        self.config = config or ScreenshotConfig()
        self._injected_page = page
        self._cookies: dict[str, str] = dict(cookies or {})
        self._playwright: Any | None = None
        self._browser: Any | None = None
        self._context: Any | None = None
        self._page: Any | None = page
        self._started = page is not None

    # -- lifecycle ----------------------------------------------------------
    async def start(self) -> None:
        """Launch headless Chromium with the configured viewport and theme."""
        if self._started:
            return
        try:
            from playwright.async_api import async_playwright
        except ImportError as exc:  # pragma: no cover - declared dependency
            raise CaptureError(
                "The 'playwright' package is required for card capture. Install "
                "dependencies and run 'playwright install chromium'."
            ) from exc

        try:
            self._playwright = await async_playwright().start()
            self._browser = await self._playwright.chromium.launch(
                headless=True,
                args=["--hide-scrollbars", "--disable-dev-shm-usage"],
            )
            self._context = await self._browser.new_context(
                viewport=self.config.viewport,  # type: ignore[arg-type]
                color_scheme=self.config.theme,
                device_scale_factor=self.config.device_scale_factor,
            )
            await self._authenticate(self._context)
            self._page = await self._context.new_page()
        except CaptureError:
            raise
        except Exception as exc:
            await self.stop()
            raise CaptureError(f"Could not launch headless Chromium: {exc}") from exc
        self._started = True
        logger.debug(
            "Playwright ready (theme=%s, viewport=%sx%s)",
            self.config.theme,
            self.config.viewport_width,
            self.config.viewport_height,
        )

    async def stop(self) -> None:
        """Tear down context, browser, and Playwright driver."""
        for closer in (
            getattr(self._context, "close", None),
            getattr(self._browser, "close", None),
            getattr(self._playwright, "stop", None),
        ):
            if callable(closer):
                try:
                    result = closer()
                    if hasattr(result, "__await__"):
                        await result
                except Exception as exc:  # pragma: no cover - teardown best effort
                    logger.debug("Ignoring teardown error: %s", exc)
        self._page = self._injected_page
        self._context = None
        self._browser = None
        self._playwright = None
        self._started = self._injected_page is not None

    async def _authenticate(self, context: Any) -> None:
        """Replay the Twitter session so X renders the permalink, not a login wall."""
        if not self._cookies:
            return
        await context.add_cookies(
            [
                {"name": name, "value": value, "domain": X_COOKIE_DOMAIN, "path": "/"}
                for name, value in self._cookies.items()
            ]
        )

    async def __aenter__(self) -> TweetCardRenderer:
        await self.start()
        return self

    async def __aexit__(self, *exc_info: Any) -> None:
        await self.stop()

    # -- capture ------------------------------------------------------------
    def output_path(self, tweet_id: str) -> Path:
        """Absolute on-disk destination for a tweet's card PNG."""
        return self.config.output_path(tweet_id)

    async def capture(self, permalink: str, tweet_id: str) -> RenderedAsset:
        """Render and capture ``permalink`` into ``{output_dir}/{tweet_id}.png``."""
        if not self._started:
            await self.start()
        if self._page is None:  # pragma: no cover - defensive
            raise CaptureError("Playwright page is not available.")
        return await self._capture_on_page(self._page, permalink, tweet_id)

    async def _capture_on_page(
        self,
        page: Any,
        permalink: str,
        tweet_id: str,
    ) -> RenderedAsset:
        target = self.output_path(tweet_id)
        target.parent.mkdir(parents=True, exist_ok=True)

        try:
            await page.goto(
                permalink,
                wait_until="domcontentloaded",
                timeout=self.config.timeout_ms,
            )
        except Exception as exc:
            raise CaptureError(
                f"Could not load tweet permalink {permalink}: {exc}"
            ) from exc

        # Wait for the card *before* injecting CSS: styling a hidden or
        # half-hydrated tree would make the visibility wait unwinnable.
        await self._wait_for_card(page, permalink)
        await self._apply_styling(page)
        await self._settle(page)

        try:
            locator = page.locator(TWEET_CARD_SELECTOR).first
            await locator.screenshot(path=str(target))
        except Exception as exc:
            raise CaptureError(
                f"Failed to screenshot the tweet card for {tweet_id}: {exc}"
            ) from exc

        if not target.exists():
            raise CaptureError(
                f"Playwright reported success but {target} was not written."
            )

        asset = RenderedAsset.from_file(target)
        logger.info(
            "Captured card %s (%dx%d, %.2f MB)",
            target.name,
            asset.width,
            asset.height,
            asset.size_in_megabytes,
        )
        return asset

    async def _apply_styling(self, page: Any) -> None:
        """Inject the theme + metric-suppression stylesheet and DOM script."""
        try:
            await page.add_style_tag(content=build_capture_styles(self.config))
        except Exception as exc:  # pragma: no cover - browser dependent
            logger.debug("Style injection failed, continuing: %s", exc)
        try:
            await page.evaluate(build_capture_script(self.config))
        except Exception as exc:  # pragma: no cover - browser dependent
            logger.debug("DOM injection failed, continuing: %s", exc)

    async def _wait_for_card(self, page: Any, permalink: str) -> None:
        try:
            await page.locator(TWEET_CARD_SELECTOR).first.wait_for(
                state="visible",
                timeout=self.config.timeout_ms,
            )
        except Exception as exc:
            raise CaptureError(
                "Could not find a tweet card at "
                f"{permalink}. The tweet may be deleted, protected, or behind a "
                f"login wall. ({exc})"
            ) from exc

    async def _settle(self, page: Any) -> None:
        wait_for_timeout = getattr(page, "wait_for_timeout", None)
        if callable(wait_for_timeout):
            try:
                await wait_for_timeout(SETTLE_MILLISECONDS)
            except Exception as exc:  # pragma: no cover - browser dependent
                logger.debug("Settle wait failed, continuing: %s", exc)


async def capture_card(
    permalink: str,
    tweet_id: str,
    config: ScreenshotConfig | None = None,
) -> RenderedAsset:
    """One-shot capture helper that manages the browser lifecycle."""
    renderer = TweetCardRenderer(config)
    try:
        return await renderer.capture(permalink, tweet_id)
    finally:
        await renderer.stop()


